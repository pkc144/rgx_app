// ─── Helper: format price ────────────────────────────────────────────────────

const formatPrice = price => {
  const num = parseFloat(price);
  return isNaN(num) ? 'N/A' : `\u20B9${num.toFixed(2)}`;
};

// ─── Helper: build common request headers ────────────────────────────────────

const getHeaders = () => ({
  'Content-Type': 'application/json',
  'X-Advisor-Subdomain': getAdvisorSubdomain(),
  'aq-encrypted-key': generateToken(
    Config.REACT_APP_AQ_KEYS,
    Config.REACT_APP_AQ_SECRET,
  ),
});

// ─── Main Component ──────────────────────────────────────────────────────────

const RebalancePreferenceModal = ({
  visible,
  onClose,
  modelName,
  userEmail,
  broker,
  userDetails,
  strategyDetails,
  onProceedToTrade,
  repairTrades,
  onContinueWithoutBroker,
}) => {
  // ── State ────────────────────────────────────────────────────────────────

  const [currentStep, setCurrentStep] = useState(1);
  const [selectedOption, setSelectedOption] = useState('option1'); // option1 = flag 1, option2 = flag 0
  const [loading, setLoading] = useState(false);
  const [holdingsLoading, setHoldingsLoading] = useState(false);
  const [error, setError] = useState(null);
  const [successMessage, setSuccessMessage] = useState(null);

  // Holdings state (step 2)
  const [holdings, setHoldings] = useState([]);
  const [editingIndex, setEditingIndex] = useState(null);
  const [editQuantity, setEditQuantity] = useState('');
  const [editPrice, setEditPrice] = useState('');
  const [apiResponseData, setApiResponseData] = useState(null);
  const [portfolioDocId, setPortfolioDocId] = useState(null);

  const hasDataBeenFetched = useRef(false);

  // ── Reset on open / close ────────────────────────────────────────────────

  useEffect(() => {
    if (visible) {
      setCurrentStep(1);
      setSelectedOption('option1');
      setLoading(false);
      setHoldingsLoading(false);
      setError(null);
      setSuccessMessage(null);
      setHoldings([]);
      setEditingIndex(null);
      setApiResponseData(null);
      setPortfolioDocId(null);
      hasDataBeenFetched.current = false;
    }
  }, [visible]);

  // ── Step 1 → Step 2 : fetch current holdings ────────────────────────────

  const handleConfirmPreference = async () => {
    setLoading(true);
    setError(null);

    try {
      // 1. Refresh broker status
      const freshUserDetails = await refreshBrokerStatus();

      // 2. Fetch current holdings for review
      await fetchCurrentHoldings();

      // Move to step 2 (Current Holdings)
      setCurrentStep(2);
    } catch (err) {
      console.error('Error confirming preference:', err);
      setError('Failed to fetch holdings. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  // ── Refresh broker status ────────────────────────────────────────────────

  const refreshBrokerStatus = async () => {
    try {
      const response = await axios.get(
        `${server.server.baseUrl}api/user/getUser/${userEmail}`,
        {headers: getHeaders()},
      );
      return response.data?.User || userDetails;
    } catch (err) {
      console.error('Error refreshing broker status:', err);
      return userDetails;
    }
  };

  // ── Fetch current holdings ───────────────────────────────────────────────

  const fetchCurrentHoldings = async () => {
    if (hasDataBeenFetched.current) return;

    setHoldingsLoading(true);
    try {
      const response = await axios.get(
        `${server.ccxtServer.baseUrl}rebalance/user-portfolio/latest/${userEmail}/${modelName}`,
        {headers: getHeaders()},
      );

      hasDataBeenFetched.current = true;
      setApiResponseData(response.data);

      // Extract portfolio doc id
      if (response.data?.data?._id?.$oid) {
        setPortfolioDocId(response.data.data._id.$oid);
      }

      // Handle user_net_pf_model (may be array – sort by execDate to get latest)
      const userNetPfModel = response.data?.data?.user_net_pf_model;
      let latestPortfolio;
      if (Array.isArray(userNetPfModel)) {
        latestPortfolio = [...userNetPfModel].sort(
          (a, b) => new Date(b.execDate) - new Date(a.execDate),
        )[0];
      } else {
        latestPortfolio = userNetPfModel;
      }

      const orderResults = latestPortfolio?.order_results || [];

      const mappedHoldings = orderResults.map((order, idx) => ({
        ...order,
        quantity: parseInt(order.quantity, 10) || 0,
        averageEntryPrice: parseFloat(order.averageEntryPrice) || 0,
        averagePrice: parseFloat(order.averagePrice) || 0,
        reactKey:
          order.uniqueOrderId || `${order.symbol}_${order.orderId || idx}`,
      }));

      setHoldings(mappedHoldings);
    } catch (err) {
      console.error('Error fetching current holdings:', err);
      setHoldings([]);
    } finally {
      setHoldingsLoading(false);
    }
  };

  // ── Edit holdings ────────────────────────────────────────────────────────

  const startEditing = index => {
    const item = holdings[index];
    setEditingIndex(index);
    setEditQuantity(String(item.quantity));
    setEditPrice(
      String(
        item.transactionType === 'BUY'
          ? item.averageEntryPrice
          : item.averagePrice,
      ),
    );
  };

  const saveEditing = () => {
    if (editingIndex === null) return;

    const updated = [...holdings];
    const item = {...updated[editingIndex]};
    item.quantity = parseInt(editQuantity, 10) || 0;

    const parsedPrice = parseFloat(editPrice) || 0;
    if (item.transactionType === 'BUY') {
      item.averageEntryPrice = parsedPrice;
    }
    item.averagePrice = parsedPrice;

    updated[editingIndex] = item;
    setHoldings(updated);
    setEditingIndex(null);
    setEditQuantity('');
    setEditPrice('');
  };

  const cancelEditing = () => {
    setEditingIndex(null);
    setEditQuantity('');
    setEditPrice('');
  };

  // ── Save updated holdings to API and proceed ────────────────────────────

  const handleConfirmHoldings = async () => {
    setLoading(true);
    setError(null);

    try {
      // Build updated response payload
      if (apiResponseData && portfolioDocId) {
        const updatedPayload = {
          data: {
            _id: {$oid: portfolioDocId},
            model_name: modelName,
            user_email: userEmail,
            user_net_pf_model: {
              order_results: holdings.map(item => {
                const {reactKey, ...rest} = item;
                return {
                  ...rest,
                  quantity: String(item.quantity),
                  filledShares: String(item.quantity),
                  transactionType: item.transactionType || 'BUY',
                  averageEntryPrice: parseFloat(item.averageEntryPrice) || 0,
                  averagePrice: parseFloat(item.averagePrice) || 0,
                };
              }),
              user_broker: broker || 'DummyBroker',
            },
          },
        };

        await axios.put(
          `${server.ccxtServer.baseUrl}rebalance/update/user-portfolio/latest`,
          updatedPayload,
          {headers: getHeaders()},
        );
      }

      // Determine flag based on selected option
      const preferenceFlag = selectedOption === 'option1' ? 1 : 0;

      // Call back to parent with preference flag and updated holdings
      if (onProceedToTrade) {
        onProceedToTrade(preferenceFlag, holdings);
      }
    } catch (err) {
      console.error('Error saving holdings:', err);
      setError('Failed to save holdings. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  // ── Repair Portfolio Flow ────────────────────────────────────────────────

  const handleRepairProceed = () => {
    if (!repairTrades) return;

    const {failedTrades} = repairTrades;
    const stockTypeAndSymbol = (failedTrades || []).map(trade => ({
      Symbol: trade.advSymbol,
      Type: trade.transactionType,
      Exchange: trade.advExchange,
      Quantity: trade.advQTY,
    }));

    const preferenceFlag = selectedOption === 'option1' ? 1 : 0;
    if (onProceedToTrade) {
      onProceedToTrade(preferenceFlag, holdings, stockTypeAndSymbol);
    }
  };

  // ── Continue Without Broker (DummyBroker flow) ──────────────────────────

  const handleContinueWithoutBroker = async () => {
    setLoading(true);
    setError(null);

    try {
      const payload = {
        userEmail,
        userBroker: 'DummyBroker',
        modelName: modelName?.trim(),
        advisor: strategyDetails?.advisor_name || strategyDetails?.advisorName,
        model_id:
          strategyDetails?.model_Id ||
          strategyDetails?.model_id ||
          strategyDetails?._id,
        userFund: '0',
        flag: selectedOption === 'option1' ? 1 : 0,
      };

      const response = await axios.post(
        `${server.ccxtServer.baseUrl}rebalance/calculate`,
        payload,
        {headers: getHeaders()},
      );

      if (onContinueWithoutBroker) {
        onContinueWithoutBroker(response.data);
      }
    } catch (err) {
      console.error('Error in DummyBroker flow:', err);
      setError('Failed to calculate rebalance. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  // ── Render: Holdings item ────────────────────────────────────────────────

  const renderHoldingItem = ({item, index}) => {
    const isEditing = editingIndex === index;
    const displayPrice =
      item.transactionType === 'BUY'
        ? item.averageEntryPrice
        : item.averagePrice;

    return (
      <View style={styles.holdingCard}>
        {/* Symbol & Exchange row */}
        <View style={styles.holdingHeader}>
          <View style={{flex: 1}}>
            <Text style={styles.holdingSymbol} numberOfLines={1}>
              {item.symbol}
            </Text>
            <Text style={styles.holdingExchange}>
              {item.exchange || 'NSE'} &bull;{' '}
              {item.transactionType || 'BUY'}
            </Text>
          </View>
          {!isEditing && (
            <TouchableOpacity
              style={styles.editButton}
              onPress={() => startEditing(index)}>
              <Edit2Icon size={14} color="#3B82F6" />
              <Text style={styles.editButtonText}>Edit</Text>
            </TouchableOpacity>
          )}
        </View>

        {isEditing ? (
          <View style={styles.editRow}>
            <View style={styles.editField}>
              <Text style={styles.editLabel}>Qty</Text>
              <TextInput
                style={styles.editInput}
                value={editQuantity}
                onChangeText={setEditQuantity}
                keyboardType="numeric"
                selectTextOnFocus
              />
            </View>
            <View style={styles.editField}>
              <Text style={styles.editLabel}>Avg Price</Text>
              <TextInput
                style={styles.editInput}
                value={editPrice}
                onChangeText={setEditPrice}
                keyboardType="decimal-pad"
                selectTextOnFocus
              />
            </View>
            <View style={styles.editActions}>
              <TouchableOpacity
                style={styles.saveBtn}
                onPress={saveEditing}>
                <CheckIcon size={16} color="#FFFFFF" />
              </TouchableOpacity>
              <TouchableOpacity
                style={styles.cancelBtn}
                onPress={cancelEditing}>
                <XIcon size={16} color="#6B7280" />
              </TouchableOpacity>
            </View>
          </View>
        ) : (
          <View style={styles.holdingDetails}>
            <View style={styles.detailCol}>
              <Text style={styles.detailLabel}>Quantity</Text>
              <Text style={styles.detailValue}>{item.quantity}</Text>
            </View>
            <View style={styles.detailCol}>
              <Text style={styles.detailLabel}>Avg Price</Text>
              <Text style={styles.detailValue}>{formatPrice(displayPrice)}</Text>
            </View>
          </View>
        )}
      </View>
    );
  };

  // ── Render: Step 1 – Preference Selection ────────────────────────────────

  const renderStep1 = () => (
    <View style={styles.stepContent}>
      <Text style={styles.stepTitle}>
        Please Choose your Rebalance Preference
      </Text>

      {/* Option 1 */}
      <TouchableOpacity
        style={[
          styles.optionCard,
          selectedOption === 'option1' && styles.optionCardSelected,
        ]}
        activeOpacity={0.7}
        onPress={() => setSelectedOption('option1')}>
        <View style={styles.optionRow}>
          <View
            style={[
              styles.checkbox,
              selectedOption === 'option1' && styles.checkboxSelected,
            ]}>
            {selectedOption === 'option1' && (
              <CheckIcon size={14} color="#FFFFFF" />
            )}
          </View>
          <View style={styles.optionTextContainer}>
            <Text style={styles.optionTitle}>
              Rebalance only those stocks where the change in allocation is more
              than 2% of your capital.
            </Text>
            <Text style={styles.optionSubtitle}>
              (This avoids small changes and helps reduce your brokerage costs.)
            </Text>
          </View>
        </View>
      </TouchableOpacity>

      {/* Option 2 */}
      <TouchableOpacity
        style={[
          styles.optionCard,
          selectedOption === 'option2' && styles.optionCardSelected,
        ]}
        activeOpacity={0.7}
        onPress={() => setSelectedOption('option2')}>
        <View style={styles.optionRow}>
          <View
            style={[
              styles.checkbox,
              selectedOption === 'option2' && styles.checkboxSelected,
            ]}>
            {selectedOption === 'option2' && (
              <CheckIcon size={14} color="#FFFFFF" />
            )}
          </View>
          <View style={styles.optionTextContainer}>
            <Text style={styles.optionTitle}>
              Rebalance the entire portfolio exactly as per the updated
              recommendation.
            </Text>
            <Text style={styles.optionSubtitle}>
              (This includes even small allocation changes and could lead to
              higher trade frequency and brokerage charges.)
            </Text>
          </View>
        </View>
      </TouchableOpacity>

      {/* Error */}
      {error && <Text style={styles.errorText}>{error}</Text>}

      {/* Action Buttons */}
      <View style={styles.buttonRow}>
        <TouchableOpacity
          style={styles.cancelButton}
          onPress={onClose}
          disabled={loading}>
          <Text style={styles.cancelButtonText}>Cancel</Text>
        </TouchableOpacity>

        <TouchableOpacity
          style={[styles.confirmButton, loading && styles.buttonDisabled]}
          onPress={handleConfirmPreference}
          disabled={loading}>
          {loading ? (
            <ActivityIndicator size="small" color="#FFFFFF" />
          ) : (
            <Text style={styles.confirmButtonText}>Confirm</Text>
          )}
        </TouchableOpacity>
      </View>

      {/* Continue Without Broker link */}
      {onContinueWithoutBroker && (
        <TouchableOpacity
          style={styles.withoutBrokerButton}
          onPress={handleContinueWithoutBroker}
          disabled={loading}>
          <Text style={styles.withoutBrokerText}>
            Continue Without Broker
          </Text>
        </TouchableOpacity>
      )}
    </View>
  );

  // ── Render: Step 2 – Current Holdings Review ─────────────────────────────

  const renderStep2 = () => (
    <View style={styles.stepContent}>
      <Text style={styles.stepTitle}>Review Your Current Holdings</Text>
      <Text style={styles.stepDescription}>
        Please review your current stock holdings in this model portfolio.
        Verify the quantities and if any information appears inaccurate, tap
        "Edit" to update them.
      </Text>

      {holdingsLoading ? (
        <View style={styles.loadingContainer}>
          <ActivityIndicator size="large" color="#0D9488" />
          <Text style={styles.loadingText}>Fetching your holdings...</Text>
        </View>
      ) : holdings.length === 0 ? (
        <View style={styles.emptyContainer}>
          <Text style={styles.emptyText}>
            No current holdings found for this model portfolio.
          </Text>
        </View>
      ) : (
        <FlatList
          data={holdings}
          renderItem={renderHoldingItem}
          keyExtractor={(item, index) => item.reactKey || `holding-${index}`}
          contentContainerStyle={styles.holdingsList}
          showsVerticalScrollIndicator={false}
          style={{maxHeight: screenHeight * 0.4}}
        />
      )}

      {/* Error */}
      {error && <Text style={styles.errorText}>{error}</Text>}

      {/* Success */}
      {successMessage && (
        <Text style={styles.successText}>{successMessage}</Text>
      )}

      {/* Action Buttons */}
      <View style={styles.buttonRow}>
        <TouchableOpacity
          style={styles.cancelButton}
          onPress={() => {
            setCurrentStep(1);
            setError(null);
          }}
          disabled={loading}>
          <Text style={styles.cancelButtonText}>Back</Text>
        </TouchableOpacity>

        {repairTrades ? (
          <TouchableOpacity
            style={[styles.confirmButton, loading && styles.buttonDisabled]}
            onPress={handleRepairProceed}
            disabled={loading}>
            {loading ? (
              <ActivityIndicator size="small" color="#FFFFFF" />
            ) : (
              <Text style={styles.confirmButtonText}>Repair Portfolio</Text>
            )}
          </TouchableOpacity>
        ) : (
          <TouchableOpacity
            style={[styles.confirmButton, loading && styles.buttonDisabled]}
            onPress={handleConfirmHoldings}
            disabled={loading}>
            {loading ? (
              <ActivityIndicator size="small" color="#FFFFFF" />
            ) : (
              <Text style={styles.confirmButtonText}>
                {holdings.length === 0 ? 'Proceed' : 'Confirm & Proceed'}
              </Text>
            )}
          </TouchableOpacity>
        )}
      </View>
    </View>
  );

  // ── Main Render ──────────────────────────────────────────────────────────

  return (
    <Modal
      visible={visible}
      animationType="fade"
      transparent
      onRequestClose={onClose}>
      <View style={styles.backdrop}>
        <View style={styles.modalContainer}>
          {/* Close button */}
          <TouchableOpacity
            style={styles.closeButton}
            onPress={onClose}
            hitSlop={{top: 10, bottom: 10, left: 10, right: 10}}>
            <XIcon size={20} color="#6B7280" />
          </TouchableOpacity>

          {/* Step Progress Bar */}
          <View style={styles.progressBarWrapper}>
            <StepProgressBar currentStep={currentStep} />
          </View>

          {/* Scrollable content */}
          <ScrollView
            showsVerticalScrollIndicator={false}
            contentContainerStyle={styles.scrollContent}
            keyboardShouldPersistTaps="handled">
            {currentStep === 1 && renderStep1()}
            {currentStep === 2 && renderStep2()}
          </ScrollView>
        </View>
      </View>
    </Modal>
  );
};

