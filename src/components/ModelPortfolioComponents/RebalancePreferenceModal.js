const StepProgressBar = ({currentStep}) => {
  const [tooltipIndex, setTooltipIndex] = useState(null);

  return (
    <View style={stepStyles.container}>
      {STEPS.map((step, index) => {
        const stepNum = index + 1;
        const isCompleted = stepNum < currentStep;
        const isActive = stepNum === currentStep;

        return (
          <React.Fragment key={index}>
            <View style={stepStyles.stepItem}>
              {/* Circle */}
              <View
                style={[
                  stepStyles.circle,
                  isCompleted && stepStyles.circleCompleted,
                  isActive && stepStyles.circleActive,
                ]}>
                {isCompleted ? (
                  <CheckCircleIcon size={14} color="#FFFFFF" />
                ) : (
                  <Text
                    style={[
                      stepStyles.circleText,
                      (isCompleted || isActive) && {color: '#FFFFFF'},
                    ]}>
                    {stepNum}
                  </Text>
                )}
              </View>

              {/* Label + Info */}
              <View style={stepStyles.labelRow}>
                <TouchableOpacity
                  onPress={() =>
                    setTooltipIndex(tooltipIndex === index ? null : index)
                  }
                  hitSlop={{top: 8, bottom: 8, left: 8, right: 8}}>
                  <InfoIcon
                    size={12}
                    color={tooltipIndex === index ? '#0D9488' : '#9CA3AF'}
                  />
                </TouchableOpacity>
                <Text
                  style={[
                    stepStyles.label,
                    isCompleted && stepStyles.labelCompleted,
                    isActive && stepStyles.labelActive,
                  ]}
                  numberOfLines={2}>
                  {step.label}
                </Text>
              </View>
            </View>

            {/* Connector line */}
            {index < STEPS.length - 1 && (
              <View
                style={[
                  stepStyles.connector,
                  isCompleted && stepStyles.connectorCompleted,
                ]}
              />
            )}
          </React.Fragment>
        );
      })}

      {/* Tooltip overlay */}
      {tooltipIndex !== null && (
        <Modal transparent visible animationType="fade">
          <TouchableOpacity
            style={stepStyles.tooltipBackdrop}
            activeOpacity={1}
            onPress={() => setTooltipIndex(null)}>
            <View style={stepStyles.tooltipCard}>
              <View style={stepStyles.tooltipHeader}>
                <Text style={stepStyles.tooltipTitle}>
                  {STEPS[tooltipIndex].label}
                </Text>
                <TouchableOpacity onPress={() => setTooltipIndex(null)}>
                  <XIcon size={16} color="#6B7280" />
                </TouchableOpacity>
              </View>
              <Text style={stepStyles.tooltipDesc}>
                {STEPS[tooltipIndex].description}
              </Text>
            </View>
          </TouchableOpacity>
        </Modal>
      )}
    </View>
  );
};

